import { categories } from './categories';

export interface Product {
  id: string;
  slug: string;
  title: string;
  name: string;
  description: string;
  price: number;
  sale_price: number | null;
  currency: 'IRR';
  sku: string;
  brand: string;
  category: string;
  stock: number;
  stock_status: 'in_stock' | 'low_stock' | 'out_of_stock';
  images: string[];
  thumbnail: string;
  rating: number;
  reviewCount: number;
  specs: Record<string, string>;
}

interface RawProduct {
  title: string;
  brand: string;
  price: number;
  salePrice: number | null;
  stock: number;
  description: string;
  image: string;
  specs: Record<string, string>;
}

function buildCategoryProducts(categorySlug: string, raws: RawProduct[]): Product[] {
  return raws.map((raw, i) => {
    const index = i + 1;
    const stockStatus: Product['stock_status'] =
      raw.stock === 0 ? 'out_of_stock' : raw.stock <= 5 ? 'low_stock' : 'in_stock';
    return {
      id: `${categorySlug}-${index}`,
      slug: `${categorySlug}-${index}`,
      title: raw.title,
      name: raw.title,
      description: raw.description,
      price: raw.price,
      sale_price: raw.salePrice,
      currency: 'IRR',
      sku: `BT-${categorySlug.slice(0, 3).toUpperCase()}-${String(index).padStart(3, '0')}`,
      brand: raw.brand,
      category: categorySlug,
      stock: raw.stock,
      stock_status: stockStatus,
      images: [
        `https://images.unsplash.com/photo-${raw.image}?w=1200&q=80`,
        `https://images.unsplash.com/photo-${raw.image}?w=800&q=80`,
      ],
      thumbnail: `https://images.unsplash.com/photo-${raw.image}?w=400&q=80`,
      rating: Math.round((3.6 + ((index * 7) % 14) / 10) * 10) / 10,
      reviewCount: 8 + ((index * 13) % 180),
      specs: raw.specs,
    };
  });
}

