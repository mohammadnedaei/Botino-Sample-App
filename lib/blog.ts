export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((p) => p.slug === slug);
}

export function getRelatedPosts(post: BlogPost, limit = 3): BlogPost[] {
  const sameTag = blogPosts.filter(
    (p) => p.slug !== post.slug && p.tags.some((t) => post.tags.includes(t))
  );
  const rest = blogPosts.filter(
    (p) => p.slug !== post.slug && !sameTag.includes(p)
  );
  return [...sameTag, ...rest].slice(0, limit);
}

export function wordCount(post: BlogPost): number {
  return post.sections
    .flatMap((s) => s.paragraphs)
    .join(' ')
    .split(/\s+/)
    .filter(Boolean).length;
}
